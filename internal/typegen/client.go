// clientPrelude holds the shapes every Content API answer shares.
const clientPrelude = `// Generated by grapi ts:generate-types. Do not edit.

export type JSONValue = string | number | boolean | null | JSONValue[] | { [key: string]: JSONValue };

export type BlocksContent = { type: string; [key: string]: unknown }[];

export interface MediaFormat {
  name: string;
  hash: string;
  ext: string;
  mime: string;
  path: string | null;
  width: number | null;
  height: number | null;
  size: number;
  sizeInBytes?: number;
  url: string;
}

export interface Media {
  id: number;
  documentId: string;
  name: string;
  alternativeText: string | null;
  caption: string | null;
  width: number | null;
  height: number | null;
  formats: Record<string, MediaFormat> | null;
  hash: string;
  ext: string | null;
  mime: string;
  size: number;
  url: string;
  previewUrl: string | null;
  provider: string;
  provider_metadata: JSONValue | null;
  createdAt: string;
  updatedAt: string;
  publishedAt: string | null;
}

export interface Pagination {
  page?: number;
  pageSize?: number;
  pageCount?: number;
  start?: number;
  limit?: number;
  total: number;
}

export interface CollectionResponse<T> {
  data: T[];
  meta: { pagination: Pagination };
}

export interface SingleResponse<T> {
  data: T;
  meta: Record<string, unknown>;
}

export interface ErrorResponse {
  data: null;
  error: { status: number; name: string; message: string; details?: JSONValue };
}

`

// Client writes api.d.ts: the JSON the Content API answers, with no
// dependency. Relations, media and components are optional because they
// are only there when populated.
func Client(set *schema.Set) string {
	var b strings.Builder
	b.WriteString(clientPrelude)
	var cts []*schema.ContentType
	// Admin types are not reachable through the Content API.
	for _, ct := range sortedContentTypes(set) {
		if !strings.HasPrefix(string(ct.UID), "admin::") {
			cts = append(cts, ct)
		}
	}
	comps := sortedComponents(set)
	known := map[string]string{}
	for _, ct := range cts {
		known[string(ct.UID)] = interfaceName(string(ct.UID))
	}
	for _, c := range comps {
		known[string(c.UID)] = interfaceName(string(c.UID))
	}
	for _, c := range comps {
		fmt.Fprintf(&b, "export interface %s {\n  id: number;\n", known[string(c.UID)])
		writeClientFields(&b, &c.Attributes, known)
		b.WriteString("}\n\n")
	}
	for _, ct := range cts {
		fmt.Fprintf(&b, "export interface %s {\n  id: number;\n  documentId: string;\n", known[string(ct.UID)])
		writeClientFields(&b, &ct.Attributes, known)
		b.WriteString("}\n\n")
	}
	b.WriteString("export interface ContentTypes {\n")
	for _, ct := range cts {
		fmt.Fprintf(&b, "  %s: %s;\n", quote(string(ct.UID)), known[string(ct.UID)])
	}
	b.WriteString("}\n\nexport interface Components {\n")
	for _, c := range comps {
		fmt.Fprintf(&b, "  %s: %s;\n", quote(string(c.UID)), known[string(c.UID)])
	}
	b.WriteString("}\n")
	return b.String()
}

func sortedContentTypes(set *schema.Set) []*schema.ContentType {
	var cts []*schema.ContentType
	for _, ct := range set.ContentTypes.All() {
		cts = append(cts, ct)
	}
	sort.Slice(cts, func(i, j int) bool { return cts[i].UID < cts[j].UID })
	return cts
}

func sortedComponents(set *schema.Set) []*schema.Component {
	var comps []*schema.Component
	for _, c := range set.Components.All() {
		comps = append(comps, c)
	}
	sort.Slice(comps, func(i, j int) bool { return comps[i].UID < comps[j].UID })
	return comps
}

func writeClientFields(b *strings.Builder, attrs *schema.OrderedMap[*schema.Attribute], known map[string]string) {
	var names []string
	for n, a := range attrs.All() {
		if !a.IsPrivate() && n != schema.AttrID && n != schema.AttrDocumentID {
			names = append(names, n)
		}
	}
	sort.Slice(names, func(i, j int) bool { return localeLess(names[i], names[j]) })
	for _, n := range names {
		a, _ := attrs.Get(n)
		t, optional := clientType(a, known)
		if a.Auto && (n == schema.AttrCreatedAt || n == schema.AttrUpdatedAt) {
			t = "string"
		}
		if optional {
			fmt.Fprintf(b, "  %s?: %s;\n", identifier(n), t)
		} else {
			fmt.Fprintf(b, "  %s: %s;\n", identifier(n), t)
		}
	}
}

var toMany = map[string]bool{
	schema.OneToMany: true, schema.ManyToMany: true, schema.ManyWay: true, schema.MorphToMany: true, schema.MorphMany: true,
}

// clientType is the attribute's type in an answer, and whether it can be
// missing from it.
func clientType(a *schema.Attribute, known map[string]string) (string, bool) {
	ref := func(uid string) string {
		if name, ok := known[uid]; ok {
			return name
		}
		return "Record<string, unknown>"
	}
	switch a.Type {
	case schema.TypeRelation:
		target := ref(a.Target)
		if a.IsMorph() {
			target = "Record<string, unknown>"
		}
		if toMany[a.Relation] {
			return target + "[]", true
		}
		return target + " | null", true
	case schema.TypeMedia:
		if a.IsMultiple() {
			return "Media[] | null", true
		}
		return "Media | null", true
	case schema.TypeComponent:
		if a.IsRepeatable() {
			return ref(a.Component) + "[]", true
		}
		return ref(a.Component) + " | null", true
	case schema.TypeDynamicZone:
		parts := make([]string, len(a.Components))
		for i, c := range a.Components {
			parts[i] = fmt.Sprintf("(%s & { __component: %s })", ref(c), quote(c))
		}
		if len(parts) == 0 {
			return "never[]", true
		}
		return "(" + strings.Join(parts, " | ") + ")[]", true
	}
	t := scalarType(a)
	if a.IsRequired() {
		return t, false
	}
	return t + " | null", false
}

func scalarType(a *schema.Attribute) string {
	switch a.Type {
	case schema.TypeInteger, schema.TypeFloat, schema.TypeDecimal:
		return "number"
	case schema.TypeBoolean:
		return "boolean"
	case schema.TypeJSON:
		return "JSONValue"
	case schema.TypeBlocks:
		return "BlocksContent"
	case schema.TypeEnumeration:
		if len(a.Enum) == 0 {
			return "string"
		}
		q := make([]string, len(a.Enum))
		for i, e := range a.Enum {
			q[i] = quote(e)
		}
		return strings.Join(q, " | ")
	case schema.TypeString, schema.TypeText, schema.TypeRichText, schema.TypeEmail, schema.TypeUID, schema.TypePassword,
		schema.TypeDate, schema.TypeTime, schema.TypeDateTime, schema.TypeTimestamp, schema.TypeBigInteger:
		return "string"
	}
	return "unknown"
}
