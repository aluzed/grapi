"""Writes compat/corpus/<fixture>_matrix.yaml: every content type's core
routes, called as Public and as an Authenticated user, so that the bench
compares the status (and body) of each role x route pair with Strapi.

usage: python3 compat/tools/gen-route-matrix.py <fixture> [compat dir]
"""
import glob
import json
import os
import sys

fixture = sys.argv[1]
root = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), "..")
cases = [
    {"name": "matrix-register", "method": "POST", "path": "/api/auth/local/register",
     "body": {"username": "matrixuser", "email": "matrix@example.com", "password": "Passw0rd!"}, "save": {"jwtm": "jwt"}},
]
for path in sorted(glob.glob(os.path.join(root, "fixtures", fixture, "src", "api", "*", "content-types", "*", "schema.json"))):
    with open(path) as f:
        schema = json.load(f)
    info = schema["info"]
    single = schema.get("kind") == "singleType"
    base = "/api/" + (info["singularName"] if single else info["pluralName"])
    calls = [("list", "GET", base, None)]
    if single:
        calls += [("put", "PUT", base, {"data": {}}), ("delete", "DELETE", base, None)]
    else:
        missing = base + "/matrixnope"
        calls += [("get", "GET", missing, None), ("post", "POST", base, {"data": {}}),
                  ("put", "PUT", missing, {"data": {}}), ("delete", "DELETE", missing, None)]
    for role in ("public", "auth"):
        for label, method, url, body in calls:
            case = {"name": f"{role}-{info['singularName']}-{label}", "method": method, "path": url}
            if body is not None:
                case["body"] = body
            if role == "auth":
                case["bearer"] = "{{jwtm}}"
            cases.append(case)

out = os.path.join(root, "corpus", f"{fixture}_matrix.yaml")
with open(out, "w") as f:
    f.write(f"fixture: {fixture}\n")
    f.write("# Generated by compat/tools/gen-route-matrix.py: role x core route.\n")
    f.write("cases:\n")
    for c in cases:
        f.write("  - " + json.dumps(c) + "\n")
print(f"{out}: {len(cases)} cases")
