// Dumps the transliteration data used by Strapi's slugify (@sindresorhus/slugify
// 1.x, @sindresorhus/transliterate, lodash.deburr) as a Go source file.
// Run inside the reference image: see internal/slug/README.md.
const path = require('path');

// Resolve from the packages themselves: lodash.deburr is nested under transliterate.
const translitDir = path.dirname(require.resolve('@sindresorhus/transliterate'));
const replacements = require(path.join(translitDir, 'replacements'));
const overridable = require('@sindresorhus/slugify/overridable-replacements');
const deburr = require(require.resolve('lodash.deburr', { paths: [translitDir] }));

const q = (s) => JSON.stringify(s);
const lines = [];
lines.push('// Code generated by compat/tools/gen-slug-tables.js; DO NOT EDIT.');
lines.push('');
lines.push('package slug');
lines.push('');
lines.push('// transliterations is applied in order, like @sindresorhus/transliterate.');
lines.push('var transliterations = [][2]string{');
const merged = new Map([...replacements, ...overridable]);
for (const [k, v] of merged) lines.push(`\t{${q(k)}, ${q(v)}},`);
lines.push('}');
lines.push('');
lines.push('// deburred maps the Latin-1 Supplement and Latin Extended-A letters lodash.deburr rewrites.');
lines.push('var deburred = map[rune]string{');
const ranges = [[0xc0, 0xd6], [0xd8, 0xf6], [0xf8, 0xff], [0x100, 0x17f]];
for (const [lo, hi] of ranges) {
  for (let c = lo; c <= hi; c++) {
    const ch = String.fromCodePoint(c);
    const out = deburr(ch);
    if (out !== ch) lines.push(`\t0x${c.toString(16)}: ${q(out)},`);
  }
}
lines.push('}');
process.stdout.write(lines.join('\n') + '\n');
